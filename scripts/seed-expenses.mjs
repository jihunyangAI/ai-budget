let added = 0;
for (const [store, date, items] of SEED) {
  const total = items.reduce((s, it) => s + it.price, 0);
  const rows = await sql`
    INSERT INTO expenses (store, date, total, items)
    SELECT ${store}, ${date}, ${total}, ${JSON.stringify(items)}::jsonb
    WHERE NOT EXISTS (SELECT 1 FROM expenses WHERE store = ${store} AND date = ${date})
    RETURNING id
  `;
  added += rows.length;
}
const [{ count }] = await sql`SELECT count(*)::int AS count FROM expenses`;
